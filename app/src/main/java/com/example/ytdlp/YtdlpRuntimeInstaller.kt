  fun getYtdlDir(context: Context): File = File(context.filesDir, YTDL_DIR).apply { if (!exists()) mkdirs() }

  fun getExecutablePath(context: Context): String =
    File(context.applicationInfo.nativeLibraryDir, "libytdl.so").absolutePath

  private val autoInstallStarted = java.util.concurrent.atomic.AtomicBoolean(false)
  private val autoInstallScope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

  /**
   * Installs yt-dlp by itself in the background right after the app is opened (once per app start), so the user never has to
   * press "Install" in Settings > Network. Nothing happens when it is already installed and ready; a failed attempt
   * (e.g. no internet) is simply tried again the next time the app starts.
   */
  fun autoInstallInBackground(context: Context) {
    if (!BuildConfig.ENABLE_YTDLP) return
    if (!autoInstallStarted.compareAndSet(false, true)) return
    val app = context.applicationContext
    autoInstallScope.launch {
      try {
        if (isPlaybackRuntimeReady(app)) {
          // already installed: only make the info shown in Settings available
          refreshInstallationInfo(app)
          return@launch
        }
        val ok = ensureRuntimeInstalled(app) { line -> Log.d(TAG, line.trim()) }
        Log.i(TAG, "Automatic yt-dlp install: " + if (ok) "done" else "failed (will retry on the next start)")
        refreshInstallationInfo(app)
      } catch (e: CancellationException) {
        throw e
      } catch (t: Throwable) {
        Log.w(TAG, "Automatic yt-dlp install failed", t)
      }
    }
  }

  suspend fun refreshInstallationInfo(context: Context): YtdlpInstallationInfo =
    withContext(Dispatchers.IO) {
      installMutex.withLock {
        readInstallationInfo(context).also { info -> _installationInfo.value = info }
      }
    }

  /**
   * `yt-dlp -J` of one link (quality/metadata list for the Online Video playback quality menu). The warm [YtdlpWorker] answers first (no Python /
   * yt-dlp start-up); only when the worker itself cannot, the one-shot yt-dlp command below is run like before.
   */
  suspend fun dumpSingleJson(
    context: Context,
    source: String,
    preferences: YtdlPreferences,
    headers: Map<String, String> = emptyMap(),
    /** A yt-dlp `--format` selection (playback: the streams that are chosen come back as `requested_formats`). */
    format: String? = null,
  ): Result<String> =
    withContext(Dispatchers.IO) {
      try {
        val args =
          buildList {
            add("--ignore-config")
            add("--dump-single-json")
            format?.takeIf { it.isNotBlank() }?.let {
              add("--format")
              add(it)
            }
            add("--no-playlist")
            add("--skip-download")
            add("--no-warnings")
            add("--no-progress")
            // a slow or dead server must not hold the whole panel back for minutes
            add("--socket-timeout")
            add("15")
            add("--extractor-retries")
            add("2")
            // YouTube: skip building the list of machine-translated caption languages (hundreds of entries nobody downloads)
            add("--extractor-args")
            add("youtube:skip=translated_subs")
            preferences.customUserAgent.get().takeIf(String::isNotBlank)?.let {
              add("--user-agent")
              add(it)
            }
            if (preferences.customUserAgent.get().isBlank()) {
              headers.entries.firstOrNull { it.key.equals("User-Agent", true) && it.value.isNotBlank() }?.let {
                add("--user-agent")
                add(it.value)
              }
            }
            (preferences.referer.get().takeIf(String::isNotBlank)
              ?: headers.entries.firstOrNull { it.key.equals("Referer", true) && it.value.isNotBlank() }?.value)?.let {
              add("--referer")
              add(it)
            }
            for ((k, v) in headers) {
              if (k.isBlank() || v.isBlank() || k.equals("User-Agent", true) || k.equals("Referer", true) || k.equals("Referrer", true)) continue
              if (k.lowercase() in setOf("host", "range", "accept-encoding", "content-length", "connection")) continue
              add("--add-header")
              add("$k:$v")
            }
            preferences.proxy.get().takeIf(String::isNotBlank)?.let {
              add("--proxy")
              add(it)
            }
            preferences.extractorArgs.get().takeIf(String::isNotBlank)?.let {
              add("--extractor-args")
              add(it)
            }
            if (preferences.geoBypass.get()) add("--geo-bypass")
            preferences.cookiesFile.get().takeIf(String::isNotBlank)?.let(::File)?.takeIf(File::isFile)?.let {
              add("--cookies")
              add(it.absolutePath)
            }
            File(context.applicationInfo.nativeLibraryDir, "libqjs.so").takeIf(File::isFile)?.let {
              add("--js-runtimes")
              add("quickjs:${it.absolutePath}")
              // same as the playback stream resolver: without the solver script the quality list only holds the reduced set that
              // the real download never sees (HLS renditions with a made-up size)
              add("--remote-components")
              add("ejs:github")
            }
          }

        // 1) the warm worker: no start-up cost after the first request
        val warm = YtdlpWorker.request(context, args, source)
        warm.getOrNull()?.let { return@withContext Result.success(it) }
        val warmError = warm.exceptionOrNull()
        if (warmError != null && warmError !is YtdlpWorkerUnavailable) return@withContext Result.failure(warmError)

        // 2) the worker could not answer: one-shot yt-dlp (the old way)
        if (!ensureRuntimeInstalled(context)) {
          return@withContext Result.failure(IllegalStateException("yt-dlp is not installed"))
        }
        val output = StringBuilder()
        val command =
          buildList {
            add(getExecutablePath(context))
            add(File(getYtdlDir(context), "yt-dlp").absolutePath)
            addAll(args)
            add("--")
            add(source)
          }
        val completed = executePlaylistExtractionProcess(command, context) { chunk -> output.append(chunk) }
        val payload =
          output
            .lineSequence()
            .map(String::trim)
            .lastOrNull { line -> line.startsWith('{') && line.endsWith('}') }
        if (!completed || payload == null) {
          val reason =
            output
              .lineSequence()
              .map(String::trim)
              .lastOrNull { it.startsWith("ERROR", ignoreCase = true) }
          return@withContext Result.failure(IllegalStateException(reason ?: "yt-dlp could not read this link"))
        }
        Result.success(payload)
      } catch (cancellation: CancellationException) {
        throw cancellation
      } catch (error: Exception) {
        Result.failure(error)
      }
    }

  /** Ensures the yt-dlp runtime is installed for yt-dlp-backed Online Video playback. */
  suspend fun ensureRuntimeInstalled(
    context: Context,
    onLog: (String) -> Unit = {},
  ): Boolean =
    withContext(Dispatchers.IO) {
      installMutex.withLock {
        if (!prepareRuntimeAssets(context, onLog)) return@withLock false
        if (isPlaybackRuntimeReady(context)) return@withLock true
        installYtdlp(context, onLog)
      }
    }

  private fun copyRuntimeAssets(context: Context, onLog: (String) -> Unit = {}): Boolean {
    val ytdlDir = getYtdlDir(context)

    // Clean up old potentially problematic scripts from multiple possible locations
    listOf("youtube-dl", "youtube-dl.sh").forEach { name ->
      File(context.filesDir, name).delete()
      File(ytdlDir, name).delete()
    }

    // Files to copy from assets/ytdl/ to filesDir/ytdl/
    val ytdlFiles = arrayOf("ytdl_env_setup.py", "python313.zip", "ytdlp_worker_loop.py")
    var copied = true
    for (name in ytdlFiles) {
      copied = copyAssetFile(context, "ytdl/$name", File(ytdlDir, name), onLog) && copied
    }

    // cacert.pem goes to filesDir/
    copied = copyAssetFile(context, "cacert.pem", File(context.filesDir, "cacert.pem"), onLog) && copied

    copyAssetFile(context, "ytdl/ytdl_launch_script", File(ytdlDir, "ytdl_launch_script"), onLog)
    // Set executable permission on wrapper (just in case it's used)
    File(ytdlDir, "ytdl_launch_script").setExecutable(true)
    return copied
  }

  private fun copyAssetFile(
    context: Context,
    assetPath: String,
    outFile: File,
    onLog: (String) -> Unit,
  ): Boolean {
    val temporaryFile = File(outFile.parentFile, "${outFile.name}.tmp")
    return try {
      context.assets.open(assetPath).use { input ->
        FileOutputStream(temporaryFile).use { output ->
          if (input.copyTo(output) == 0L) throw IOException("Bundled asset is empty: $assetPath")
          output.fd.sync()
        }
        if (!temporaryFile.renameTo(outFile)) throw IOException("Could not replace bundled asset: $assetPath")
        Log.d(TAG, "Copied asset: $assetPath")
        true
      }
    } catch (e: IOException) {
      Log.e(TAG, "Failed to copy asset: $assetPath", e)
      onLog("$assetPath: ${e.message}\n")
      false
    } finally {
      temporaryFile.delete()
    }
  }

  /**
   * ytdl_hook reads its executable path when libmpv starts built-in Lua scripts. A core may
   * already exist for a local file when a web URL arrives, so these app-owned script options
   * must be written before MPVLib.init(), not after the first failed YouTube load.
   * Python/yt-dlp installation and network operations remain deferred to web playback.
   */
  fun configureMpvHookBeforeInit(context: Context) {
    if (!BuildConfig.ENABLE_YTDLP) {
      mpvOption("ytdl", "no")
      return
    }
    val ytdlBinaryPath = getExecutablePath(context)
    val allFormats = "yes"
    // Configure the bundled hook before MPVLib.init(), otherwise it caches an empty path.
    // Keep a generated fallback for ytdl_hook. This file is app-owned compatibility state, not a
    // user preference: mpv.conf ownership must never delete it or leave a stale bundled path
    // behind. A genuinely hand-written hook file is preserved and the required bootstrap values
    // are supplied independently through app-owned script options below.
    try {
      val scriptOptsDir = File(context.filesDir, "script-opts")
      if (!scriptOptsDir.exists()) scriptOptsDir.mkdirs()
      val ytdlConf = File(scriptOptsDir, "ytdl_hook.conf")
      val existingContent = ytdlConf.takeIf(File::isFile)?.readText().orEmpty()
      val generatedConfig =
        existingContent.startsWith(GENERATED_HOOK_CONFIG_MARKER) ||
          isLegacyGeneratedHookConfig(existingContent)

      when {
        existingContent.isNotBlank() && !generatedConfig -> Log.d(TAG, "Preserving user-supplied ytdl_hook.conf")
        else -> {
          val confLines =
            buildList {
              add(GENERATED_HOOK_CONFIG_MARKER)
              add("ytdl_path=$ytdlBinaryPath")
              add("all_formats=$allFormats")
              add("force_all_formats=yes")
              add("try_ytdl_first=yes")
              add("exclude=$DIRECT_MEDIA_EXCLUDE")
            }
          val desiredContent = confLines.joinToString("\n", postfix = "\n")
          if (existingContent != desiredContent) {
            ytdlConf.writeText(desiredContent)
            Log.d(TAG, "Updated generated ytdl_hook.conf at ${ytdlConf.absolutePath}")
          }
        }
      }
    } catch (e: Exception) {
      Log.e(TAG, "Failed to create ytdl_hook.conf", e)
    }

    applyMpvHookOptions(context, enableHook = false)
  }

  private fun applyMpvHookOptions(
    context: Context,
    enableHook: Boolean,
  ) {
    val ytdlBinaryPath = getExecutablePath(context)

    // These values are part of mpvRx's bundled bridge contract. They intentionally bypass
    // preference ownership so a broad script-opts override cannot remove half of the integration.
    mpvOption("script-opts-append", "ytdl_hook-ytdl_path=$ytdlBinaryPath")
    mpvOption("script-opts-append", "ytdl_hook-all_formats=yes")
    mpvOption("script-opts-append", "ytdl_hook-force_all_formats=yes")
    mpvOption("script-opts-append", "ytdl_hook-try_ytdl_first=yes")
    // Skip yt-dlp for direct media/manifest URLs (.m3u8/.mpd/.mp4/.ts/...). Without this,
    // ytdl_hook intercepts every http(s) URL and routes it through yt-dlp's generic
    // extractor, which chokes on tokenized HLS/CDN links — so mpv never falls back to
    // ffmpeg's native HLS demuxer and playback fails (while MX Player/VLC play it fine).
    mpvOption("script-opts-append", "ytdl_hook-exclude=$DIRECT_MEDIA_EXCLUDE")
    // Viaura keeps the hook OFF for everything except links it routes to yt-dlp itself, so
    // NewPipe/HLS/direct streams (extension-less CDN URLs) are never hijacked by ytdl_hook.
    mpvOption("ytdl", if (enableHook) "yes" else "no")
  }

  private fun isLegacyGeneratedHookConfig(content: String): Boolean {
    if (content.isBlank()) return false
    val options =
      content
        .lineSequence()
        .map(String::trim)
        .filter { it.isNotEmpty() && !it.startsWith("#") }
        .mapNotNull { line ->
          val separator = line.indexOf('=')
          if (separator <= 0) null else line.take(separator).trim() to line.drop(separator + 1).trim()
        }.toMap()
    return options.keys ==
      setOf("ytdl_path", "all_formats", "force_all_formats", "try_ytdl_first", "exclude") &&
      !options["ytdl_path"].isNullOrBlank() &&
      options["all_formats"] == "yes" &&
      options["force_all_formats"] == "yes" &&
      options["try_ytdl_first"] == "yes" &&
      options["exclude"] == DIRECT_MEDIA_EXCLUDE
  }

  /**
   * The native pieces yt-dlp runs on: libytdl.so (the bridge, built from src/main/cpp) loads libpython.so at run time. They
   * are packaged per ABI by Gradle (src/ytdlp/jniLibs/<abi>/). When one is missing from the APK the process dies with
   * "Could not load libpython.so: dlopen failed" — this check reports the real cause (and which file) BEFORE starting it.
   */
  private fun missingNativeRuntime(context: Context): List<String> {
    val nativeLibDir = File(context.applicationInfo.nativeLibraryDir)
    return listOf("libytdl.so", "libpython.so", "libqjs.so").filter { !File(nativeLibDir, it).isFile }
  }

  private fun nativeRuntimeReady(context: Context, onLog: (String) -> Unit): Boolean {
    val missing = missingNativeRuntime(context)
    if (missing.isEmpty()) return true
    val abi = android.os.Build.SUPPORTED_ABIS.firstOrNull().orEmpty()
    onLog(
      "yt-dlp runtime is incomplete: ${missing.joinToString()} missing from this APK ($abi).\n" +
        "Rebuild the app so that app/src/ytdlp/jniLibs/$abi/libpython.so is packaged (see the build-apk.yml step " +
        "\"Fetch libpython.so\").\n",
    )
    return false
  }

  suspend fun runInstall(
    context: Context,
    onLog: (String) -> Unit,
  ): Boolean =
    withContext(Dispatchers.IO) {
      installMutex.withLock {
        if (!nativeRuntimeReady(context, onLog)) return@withLock false
        if (!prepareRuntimeAssets(context, onLog)) return@withLock false
        installYtdlp(context, onLog)
      }
    }

  suspend fun runUpdate(
    context: Context,
    onLog: (String) -> Unit,
  ): Boolean =
    withContext(Dispatchers.IO) {
      installMutex.withLock {
        if (!nativeRuntimeReady(context, onLog)) return@withLock false
        if (!prepareRuntimeAssets(context, onLog) || !isInstalled(context)) {
          _installationInfo.value = readInstallationInfo(context)
          return@withLock false
        }

        val ytdlDir = getYtdlDir(context)
        val pythonBinary = getExecutablePath(context)
        val ytDlp = File(ytdlDir, "yt-dlp").absolutePath
        if (!BuildConfig.ENABLE_YTDLP) return@withLock false
        val direct = updateDirect(context, nightly = false, onLog = onLog)
        val command = mutableListOf(pythonBinary, ytDlp, "--update")
        val updated = direct ?: runPythonProcess("Updating yt-dlp...", command, context, onLog)
        if (updated) {
          markPlaybackRuntimeReady(context)
        }
        _installationInfo.value = readInstallationInfo(context)
        updated
      }
    }

  suspend fun runUpdateToNightly(
    context: Context,
    onLog: (String) -> Unit,
  ): Boolean =
    withContext(Dispatchers.IO) {
      installMutex.withLock {
        if (!nativeRuntimeReady(context, onLog)) return@withLock false
        if (!prepareRuntimeAssets(context, onLog) || !isInstalled(context)) {
          _installationInfo.value = readInstallationInfo(context)
          return@withLock false
        }

        val ytdlDir = getYtdlDir(context)
        val pythonBinary = getExecutablePath(context)
        val ytDlp = File(ytdlDir, "yt-dlp").absolutePath
        if (!BuildConfig.ENABLE_YTDLP) return@withLock false
        val direct = updateDirect(context, nightly = true, onLog = onLog)
        val command = mutableListOf(pythonBinary, ytDlp, "--update-to", "nightly")
        val updated = direct ?: runPythonProcess("Updating to yt-dlp nightly...", command, context, onLog)
        if (updated) {
          markPlaybackRuntimeReady(context)
        }
        _installationInfo.value = readInstallationInfo(context)
        updated
      }
    }

  private suspend fun prepareRuntimeAssets(
    context: Context,
    onLog: (String) -> Unit,
  ): Boolean {
    if (!runtimeAssetsPrepared) {
      runtimeAssetsPrepared = copyRuntimeAssets(context, onLog)
    }
    if (!runtimeAssetsPrepared) onLog("Failed to prepare the bundled yt-dlp runtime assets.\n")
    return runtimeAssetsPrepared
  }

  fun isInstalled(context: Context): Boolean {
    val ytDlp = File(getYtdlDir(context), "yt-dlp")
    return ytDlp.isFile && ytDlp.length() > 0L
  }

  private fun readInstallationInfo(context: Context): YtdlpInstallationInfo {
    if (!isInstalled(context)) return YtdlpInstallationInfo.NotInstalled

    val ytdlFile = File(getYtdlDir(context), "yt-dlp")
    // read from the zip itself: instant (the Python way below needs two process starts)
    zipInfo(ytdlFile)?.let { info ->
      return YtdlpInstallationInfo(
        isInstalled = true,
        version = info["version"],
        channel = YtdlpReleaseChannel.resolve(info["channel"], info["origin"], info["version"]),
        commitHash = info["release_git_head"]?.takeIf { it.isNotBlank() },
        origin = info["origin"]?.takeIf { it.isNotBlank() },
        variant = info["variant"]?.takeIf { it.isNotBlank() },
      )
    }
    val metadataOutput = StringBuilder()
    val metadataRead =
      executePythonProcess(
        command =
          listOf(
            getExecutablePath(context),
            "-c",
            installationInfoScript,
            ytdlFile.absolutePath,
          ),
        context = context,
      ) { line -> metadataOutput.appendLine(line) }
    if (metadataRead) {
      metadataOutput
        .lineSequence()
        .lastOrNull { line -> line.startsWith(INSTALLATION_INFO_PREFIX) }
        ?.removePrefix(INSTALLATION_INFO_PREFIX)
        ?.let(::parseInstallationInfo)
        ?.let { return it }
    }

    val versionOutput = StringBuilder()
    val versionRead =
      executePythonProcess(
        command = listOf(getExecutablePath(context), ytdlFile.absolutePath, "--version"),
        context = context,
      ) { line -> versionOutput.appendLine(line) }
    val version =
      versionOutput
        .lineSequence()
        .map(String::trim)
        .firstOrNull { line -> line.matches(Regex("""\d+(?:\.\d+)+""")) }
        .takeIf { versionRead }
    return YtdlpInstallationInfo(
      isInstalled = true,
      version = version,
      channel = YtdlpReleaseChannel.resolve(channel = null, origin = null, version = version),
    )
  }

  private fun parseInstallationInfo(payload: String): YtdlpInstallationInfo? =
    runCatching {
      val json = JSONObject(payload)
      val version = json.optionalString("version")
      val channel = json.optionalString("channel")
      val origin = json.optionalString("origin")
      YtdlpInstallationInfo(
        isInstalled = true,
        version = version,
        channel = YtdlpReleaseChannel.resolve(channel, origin, version),
        commitHash = json.optionalString("commit"),
        origin = origin,
        variant = json.optionalString("variant"),
      )
    }.onFailure { error ->
      Log.w(TAG, "Failed to parse installed yt-dlp metadata", error)
    }.getOrNull()

  private fun JSONObject.optionalString(key: String): String? =
    optString(key)
      .trim()
      .takeIf { value -> value.isNotEmpty() && !value.equals("null", ignoreCase = true) }

  private fun isPlaybackRuntimeReady(context: Context): Boolean =
    isInstalled(context) &&
      File(getYtdlDir(context), PLAYBACK_RUNTIME_VERSION_FILE).readTextOrNull() == PLAYBACK_RUNTIME_VERSION

  private fun markPlaybackRuntimeReady(context: Context) {
    runCatching {
      File(getYtdlDir(context), PLAYBACK_RUNTIME_VERSION_FILE).writeText(PLAYBACK_RUNTIME_VERSION)
    }.onFailure { error ->
      Log.w(TAG, "Failed to persist yt-dlp playback runtime version", error)
    }
  }

  private fun File.readTextOrNull(): String? =
    runCatching { takeIf(File::isFile)?.readText()?.trim() }.getOrNull()

  private fun installYtdlp(
    context: Context,
    onLog: (String) -> Unit,
  ): Boolean {
    if (!BuildConfig.ENABLE_YTDLP) return false
    val target = File(getYtdlDir(context), "yt-dlp")
    // 1) the yt-dlp that the build already put into the app: copying it takes a moment (no download, no Python start)
    var installed = installBundled(context, target, onLog)
    // 2) a direct download (no Python start, validated as a zip before it replaces anything)
    if (!installed) {
      onLog("Installing yt-dlp (this build has no bundled copy)...\n")
      installed =
        downloadYtdlp(RELEASE_STABLE, target, onLog) ||
          downloadYtdlpFromPypi(target, onLog) ||
          downloadYtdlp(RELEASE_NIGHTLY, target, onLog)
    }
    // 3) last resort: the old Python based installer
    if (!installed) {
      val ytdlDir = getYtdlDir(context)
      val command = mutableListOf(getExecutablePath(context), File(ytdlDir, "ytdl_env_setup.py").absolutePath, context.applicationInfo.nativeLibraryDir)
      installed = runPythonProcess("Installing yt-dlp...", command, context, onLog) && isInstalled(context)
    }
    if (installed) {
      markPlaybackRuntimeReady(context)
      YtdlpWorker.stop()
    }
    _installationInfo.value = readInstallationInfo(context)
    if (installed) YtdlpWorker.prewarm(context)
    return installed
  }

  private fun installBundled(
    context: Context,
    target: File,
    onLog: (String) -> Unit,
  ): Boolean {
    val tmp = File(target.parentFile, "yt-dlp.bundled")
    return try {
      context.assets.open(BUNDLED_ASSET).use { input ->
        FileOutputStream(tmp).use { output -> input.copyTo(output, 64 * 1024) }
      }
      if (!isValidYtdlpZip(tmp)) {
        tmp.delete()
        false
      } else {
        tmp.setReadable(true, true)
        tmp.setWritable(true, true)
        if (!tmp.renameTo(target)) throw IOException("could not move yt-dlp into place")
        onLog("yt-dlp ${zipInfo(target)?.get("version").orEmpty()} installed.\n")
        true
      }
    } catch (e: Exception) {
      // no bundled copy in this build (or a broken one): the download below is used
      tmp.delete()
      false
    }
  }

  /** A yt-dlp zipapp: opens as a zip and holds yt_dlp/version.py (checking this takes milliseconds, running it takes seconds). */
  private fun isValidYtdlpZip(file: File): Boolean =
    file.isFile && file.length() > 500_000L &&
      runCatching { java.util.zip.ZipFile(file).use { it.getEntry("yt_dlp/version.py") != null && it.getEntry("__main__.py") != null } }
        .getOrDefault(false)

  /** version / channel / commit / origin read straight out of the zip. */
  private fun zipInfo(file: File): Map<String, String>? =
    runCatching {
      java.util.zip.ZipFile(file).use { zip ->
        val entry = zip.getEntry("yt_dlp/version.py") ?: return@use null
        val text = zip.getInputStream(entry).bufferedReader().use { it.readText() }
        val out = HashMap<String, String>()
        for (key in listOf("__version__", "RELEASE_GIT_HEAD", "CHANNEL", "ORIGIN", "VARIANT")) {
          Regex("^" + key + """\s*=\s*['"]([^'"]*)['"]""", RegexOption.MULTILINE).find(text)?.let {
            out[if (key == "__version__") "version" else key.lowercase()] = it.groupValues[1]
          }
        }
        out.takeIf { it.containsKey("version") }
      }
    }.getOrNull()

  private fun latestTag(releaseUrl: String): String? = YtdlpFetch.latestTag(releaseUrl)

  /** Downloads the newest yt-dlp of [releaseUrl] next to [target] and swaps it in only when it is a valid yt-dlp. */
  private fun downloadYtdlp(
    releaseUrl: String,
    target: File,
    onLog: (String) -> Unit,
  ): Boolean = fetchYtdlp(target, onLog, "GitHub") { tmp -> YtdlpFetch.download("$releaseUrl/download/yt-dlp", tmp) }

  /** The same release from PyPI (another host: works when github.com does not). */
  private fun downloadYtdlpFromPypi(
    target: File,
    onLog: (String) -> Unit,
  ): Boolean = fetchYtdlp(target, onLog, "PyPI") { tmp -> YtdlpFetch.downloadFromPypi(tmp) }

  private fun fetchYtdlp(
    target: File,
    onLog: (String) -> Unit,
    sourceName: String,
    fetch: (File) -> Unit,
  ): Boolean {
    val tmp = File(target.parentFile, "yt-dlp.download")
    repeat(2) { attempt ->
      try {
        tmp.delete()
        fetch(tmp)
        if (!isValidYtdlpZip(tmp)) throw IOException("the downloaded file is not a yt-dlp release")
        tmp.setReadable(true, true)
        tmp.setWritable(true, true)
        if (!tmp.renameTo(target)) throw IOException("could not move yt-dlp into place")
        onLog("yt-dlp ${zipInfo(target)?.get("version").orEmpty()} downloaded ($sourceName).\n")
        return true
      } catch (e: Exception) {
        tmp.delete()
        Log.w(TAG, "yt-dlp download from $sourceName, attempt ${attempt + 1}: ${e.message}")
        if (attempt == 0) Thread.sleep(500L) else onLog("$sourceName: ${e.message}\n")
      }
    }
    return false
  }

  /** Update to the newest release of the channel: nothing is downloaded when the installed version is already it. */
  private fun updateDirect(
    context: Context,
    nightly: Boolean,
    onLog: (String) -> Unit,
  ): Boolean? {
    val target = File(getYtdlDir(context), "yt-dlp")
    val releaseUrl = if (nightly) RELEASE_NIGHTLY else RELEASE_STABLE
    val installed = zipInfo(target)
    val installedVersion = installed?.get("version")
    val installedNightly = installed?.get("origin")?.contains("nightly", true) == true
    onLog(if (nightly) "Checking for yt-dlp nightly...\n" else "Checking for yt-dlp updates...\n")
    val latest = latestTag(releaseUrl)
    if (latest != null && latest == installedVersion && installedNightly == nightly) {
      onLog("yt-dlp is already the latest version ($latest).\n")
      return true
    }
    if (!downloadYtdlp(releaseUrl, target, onLog) && !(!nightly && downloadYtdlpFromPypi(target, onLog))) return null
    markPlaybackRuntimeReady(context)
    YtdlpWorker.stop()
    return true
  }

  private fun runPythonProcess(
    title: String,
    command: List<String>,
    context: Context,
    onLog: (String) -> Unit,
  ): Boolean {
    onLog("$title\n")
    return executePythonProcess(command, context) { line -> onLog("$line\n") }
  }

  private fun executePythonProcess(
    command: List<String>,
    context: Context,
    onOutput: (String) -> Unit,
  ): Boolean {
    return try {
      val process = startPythonProcess(command, context)

      BufferedReader(InputStreamReader(process.inputStream)).use { reader ->
        reader.lineSequence().forEach(onOutput)
      }
      process.waitFor() == 0
    } catch (e: Exception) {
      onOutput("Error: ${e.message}")
      false
    }
  }

  private suspend fun executePlaylistExtractionProcess(
    command: List<String>,
    context: Context,
    onOutput: (String) -> Unit,
  ): Boolean =
    coroutineScope {
      val process = startPythonProcess(command, context)
      val outputJob =
        async(Dispatchers.IO) {
          var outputChars = 0L
          InputStreamReader(process.inputStream).use { reader ->
            val buffer = CharArray(DEFAULT_BUFFER_SIZE)
            while (true) {
              val count = reader.read(buffer)
              if (count < 0) break
              outputChars += count
              check(outputChars <= MAX_PLAYLIST_OUTPUT_CHARS) { "Playlist metadata is too large" }
              onOutput(String(buffer, 0, count))
            }
          }
        }
      val exitJob = async(Dispatchers.IO) { runInterruptible { process.waitFor() } }

      try {
        withTimeoutOrNull(PLAYLIST_EXTRACTION_TIMEOUT_MS) {
          val exitCode = exitJob.await()
          outputJob.await()
          exitCode == 0
        } ?: throw IllegalStateException("Playlist import timed out")
      } finally {
        if (process.isAlive) process.destroyForcibly()
        runCatching { process.inputStream.close() }
        outputJob.cancel()
        exitJob.cancel()
      }
    }

  internal fun startPythonProcess(
    command: List<String>,
    context: Context,
    mergeStderr: Boolean = true,
  ): Process {
    val processBuilder =
      ProcessBuilder(command)
        .directory(getYtdlDir(context))
        .redirectErrorStream(mergeStderr)
    val env = processBuilder.environment()
    val ytdlDir = getYtdlDir(context).absolutePath
    val nativeLibDir = context.applicationInfo.nativeLibraryDir

    // Clear YTDL_SCRIPT so the bridge doesn't try to wrap yt-dlp during setup/update.
    env.remove("YTDL_SCRIPT")
    env["YTDL_PYTHON"] = File(nativeLibDir, "libpython.so").absolutePath
    env["PYTHONHOME"] = ytdlDir
    env["PYTHONPATH"] = "$ytdlDir/python313.zip:$ytdlDir:$nativeLibDir"
    env["HOME"] = context.filesDir.absolutePath
    env["XDG_CACHE_HOME"] = context.cacheDir.absolutePath
    env["TMPDIR"] = context.cacheDir.absolutePath
    env["SSL_CERT_FILE"] = File(context.filesDir, "cacert.pem").absolutePath
    env["LD_LIBRARY_PATH"] = nativeLibDir
    return processBuilder.start()
  }
